/** M05 authentic Phaser 4.2.1/Chromium screenshot QA, NOT an image synthesizer.
 * Requires serve branch public/ via HTTP, Playwright + Chromium installed in approved QA.
 * Example: node public/official/src/maps-visual/m01/m05/capture-m05.mjs http://127.0.0.1:8080
 * Fails non-zero with no fabricated screenshot if runtime is unavailable.
 */
import {mkdir,writeFile} from "node:fs/promises";
import {resolve} from "node:path";
const base=(process.argv[2]||"http://127.0.0.1:8080").replace(/\/$/,"");
const root=base+"/official/art/maps/m01/m05/index.html";
const out=resolve("docs/art/maps/evidencias/M05");
let chromium;
try{({chromium}=await import("playwright"));}
catch(e){console.error("NOT_RUN: Playwright browser QA not installed in this environment.");process.exit(2);}
await mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true,args:["--use-gl=angle","--use-angle=swiftshader","--enable-webgl","--ignore-gpu-blocklist"]});
const records=[];
try{
 for(const viewport of [{width:1280,height:768},{width:844,height:390},{width:932,height:430}]){
  for(const mode of ["m04","bucolico","contraste"]){
   const context=await browser.newContext({viewport,deviceScaleFactor:1});
   const page=await context.newPage();
   const errors=[];page.on("pageerror",e=>errors.push(e.message));
   page.on("response",r=>{if(r.status()>=400)errors.push("HTTP "+r.status()+" "+r.url());});
   const url=root+"?mode="+mode+"&palette=equilibrada";
   await page.goto(url,{waitUntil:"networkidle",timeout:60000});
   await page.locator("#blocker").waitFor({state:"hidden",timeout:30000});
   const renderer=await page.locator("#runtime").textContent();
   if(!/WebGL2 real/.test(renderer||""))throw Error("NO_WEBGL2 "+url+" "+renderer);
   if(errors.length)throw Error("BROWSER_ERRORS "+url+" "+errors.join("; "));
   const name=mode+"_"+viewport.width+"x"+viewport.height+"_PHASER_WEBGL2_REAL.png";
   await page.screenshot({path:resolve(out,name),animations:"disabled"});
   records.push({path:"docs/art/maps/evidencias/M05/"+name,mode,viewport,renderer,
     type:"REAL_BROWSER_CAPTURE",url,device:"Chromium SwiftShader, NOT physical iPhone/Android"});
   console.log("REAL_SCREENSHOT",name);
   await context.close();
  }
 }
 await writeFile(resolve(out,"capture-index.json"),JSON.stringify({
  schema:"m05-capture-index-v1",generatedAt:new Date().toISOString(),
  shots:records,physicalDevice:false,integratedTowersActors:false,
  note:"Scene contains map visual fixtures only. Integrated C1D2 screenshot must be separately generated by Integrator."
 },null,2)+"\n");
 console.log(JSON.stringify({status:"PASS_REAL_CHROMIUM_ONLY",screenshots:records.length,index:resolve(out,"capture-index.json")},null,2));
}finally{await browser.close();}
